// Pure Kotlin/JVM core: the RFC 9421 profile (signature base, Content-Digest, envelope) implemented once (E1).
// No runtime dependency besides the Kotlin stdlib; crypto only through java.security (tests).
plugins {
    id("org.jetbrains.kotlin.jvm")
    `maven-publish`
}

kotlin {
    jvmToolchain(17)
}

dependencies {
    testImplementation("junit:junit:4.13.2")
}

publishing {
    publications {
        create<MavenPublication>("release") {
            from(components["java"])
            artifactId = "core"
        }
    }
    repositories {
        maven {
            name = "localRepo"
            url = uri(rootProject.layout.buildDirectory.dir("repo"))
        }
    }
}

// Shared SDK-VEC vectors (verification/sdk/vectors): generated by verification/sdk/gen_vectors.py.
val vectorsDir: File = rootDir.resolve("../../verification/sdk/vectors").canonicalFile

tasks.test {
    systemProperty("sentomaru.vectors.dir", vectorsDir.path)
    inputs.dir(vectorsDir).withPathSensitivity(PathSensitivity.RELATIVE)
}

// Signs every positive vector with this core and a fresh JDK key and rewrites core-signed-v1.json, consumed by
// the server tests (server path) and verification/sdk/check_vectors.py. Run after changing the core or the vectors.
tasks.register<JavaExec>("exportCoreSignedVectors") {
    group = "verification"
    description = "Writes verification/sdk/vectors/core-signed-v1.json (core-signed SDK-VEC fixture)."
    classpath = sourceSets["test"].runtimeClasspath
    mainClass.set("br.com.ebees.sentomaru.core.CoreSignedVectorsKt")
    args(vectorsDir.path)
}
