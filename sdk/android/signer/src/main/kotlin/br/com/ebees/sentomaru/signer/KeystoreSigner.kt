package br.com.ebees.sentomaru.signer

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import java.math.BigInteger
import java.security.GeneralSecurityException
import java.security.KeyPairGenerator
import java.security.KeyStore
import java.security.PrivateKey
import java.security.ProviderException
import java.security.Signature
import java.security.interfaces.ECPublicKey
import java.security.spec.ECGenParameterSpec

/** Outcome of key generation; StrongBox absence is an expected result, not a crash. */
sealed interface GenerationResult {
    /** Attestation certificate chain, DER, leaf first (as returned by AndroidKeyStore). */
    class Generated(val chain: List<ByteArray>) : GenerationResult
    data object StrongBoxUnavailable : GenerationResult
}

/** Thrown only by [KeystoreSigner.generate]; use [KeystoreSigner.generateResult] to branch without exceptions. */
class StrongBoxUnavailableError : IllegalStateException("StrongBox unavailable on this device")

/**
 * LAB ONLY (Sentomaru P0b). Generates a non-exportable EC P-256 signing key in AndroidKeyStore
 * with Key Attestation and signs RFC 9421 signature bases as 64-byte P1363 ECDSA (SHA-256).
 *
 * Lab-only limits:
 * - `setUserAuthenticationRequired(false)`: the key is usable without biometric/PIN so the
 *   instrumented tests can run unattended. A product build must decide per operation whether
 *   user authentication is required; this choice is not a product decision.
 * - The attestation chain is returned as-is; its trust (Google roots, challenge, key match,
 *   boot state) is decided only by the server verifier, never on the device.
 *
 * Not thread-safe: an instance holds the alias bound by the last successful generation;
 * callers must serialize `generate*`/`sign` on the same instance.
 */
class KeystoreSigner {
    private var alias: String? = null

    /**
     * Generates a key under [alias] and returns the chain or a typed StrongBox result.
     *
     * Any existing key under [alias] is deleted BEFORE generating; if generation then fails
     * (StrongBox unavailable or any other error) the previous key is lost. Calling this always
     * unbinds the instance first, so after any failure [sign] throws `IllegalStateException`
     * until a later generation succeeds.
     */
    fun generateResult(alias: String, challenge: ByteArray, strongBox: Boolean): GenerationResult {
        this.alias = null
        require(alias.isNotEmpty()) { "alias must not be empty" }
        require(challenge.size == ATTESTATION_CHALLENGE_BYTES) {
            "attestationChallenge must be $ATTESTATION_CHALLENGE_BYTES raw bytes"
        }
        deleteKey(alias)
        val spec = KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_SIGN)
            .setAlgorithmParameterSpec(ECGenParameterSpec("secp256r1"))
            .setDigests(KeyProperties.DIGEST_SHA256)
            .setAttestationChallenge(challenge.copyOf())
            .setUserAuthenticationRequired(false) // LAB ONLY, see class doc.
            .apply { if (strongBox) setIsStrongBoxBacked(true) }
            .build()
        try {
            KeyPairGenerator.getInstance(KeyProperties.KEY_ALGORITHM_EC, ANDROID_KEYSTORE).run {
                initialize(spec)
                generateKeyPair()
            }
        } catch (e: StrongBoxUnavailableException) {
            deleteKey(alias)
            return GenerationResult.StrongBoxUnavailable
        } catch (e: ProviderException) {
            // Some devices wrap the StrongBox failure in a ProviderException.
            deleteKey(alias)
            if (strongBox && e.cause is StrongBoxUnavailableException) return GenerationResult.StrongBoxUnavailable
            throw e
        }
        val chain = keyStore().getCertificateChain(alias)
            ?: error("AndroidKeyStore returned no certificate chain for generated key")
        this.alias = alias
        return GenerationResult.Generated(chain.map { it.encoded })
    }

    /** Interface from the P0b plan: certificate chain DER, leaf first. */
    fun generate(alias: String, challenge: ByteArray, strongBox: Boolean): List<ByteArray> =
        when (val r = generateResult(alias, challenge, strongBox)) {
            is GenerationResult.Generated -> r.chain
            GenerationResult.StrongBoxUnavailable -> throw StrongBoxUnavailableError()
        }

    /**
     * Binds this instance to a key already present in AndroidKeyStore under [alias] (for example
     * generated by an earlier process). Unbinds first and stays unbound on any failure:
     * `IllegalStateException` if no private key exists under [alias] or the keystore cannot load it
     * (`KeyStoreException`/`UnrecoverableKeyException`/other `GeneralSecurityException`);
     * `IllegalArgumentException` if the key is not EC P-256.
     */
    fun useExisting(alias: String) {
        this.alias = null
        require(alias.isNotEmpty()) { "alias must not be empty" }
        val (key, publicKey) = try {
            val ks = keyStore()
            ks.getKey(alias, null) to ks.getCertificate(alias)?.publicKey
        } catch (e: GeneralSecurityException) {
            throw IllegalStateException("key under alias unavailable", e)
        }
        if (key !is PrivateKey) throw IllegalStateException("no key under alias")
        require(publicKey is ECPublicKey && publicKey.params.order == P256_ORDER &&
            publicKey.params.curve.field.fieldSize == 256) { "key under alias is not EC P-256" }
        this.alias = alias
    }

    /** Signs [signatureBase] (RFC 9421 base bytes) and returns 64-byte P1363 `r || s`. */
    fun sign(signatureBase: ByteArray): ByteArray {
        val a = alias ?: throw IllegalStateException("no key generated")
        val key = keyStore().getKey(a, null) as? PrivateKey
            ?: throw IllegalStateException("no key generated")
        val der = Signature.getInstance(SIGNATURE_ALGORITHM).run {
            initSign(key)
            update(signatureBase)
            sign()
        }
        return EcdsaSignatureFormat.derToP1363(der)
    }

    companion object {
        const val ATTESTATION_CHALLENGE_BYTES = 32
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val SIGNATURE_ALGORITHM = "SHA256withECDSA"
        private val P256_ORDER = BigInteger("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551", 16)

        private fun keyStore(): KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

        fun deleteKey(alias: String) {
            val ks = keyStore()
            if (ks.containsAlias(alias)) ks.deleteEntry(alias)
        }

        fun containsAlias(alias: String): Boolean = keyStore().containsAlias(alias)
    }
}
